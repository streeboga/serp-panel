        'her', 'his', 'i', 'if', 'in', 'is', 'it', 'its', 'of', 'on', 'or', 'that', 'the', 'their',
        'them', 'there', 'these', 'they', 'this', 'to', 'was', 'were', 'will', 'with', 'you', 'your',
